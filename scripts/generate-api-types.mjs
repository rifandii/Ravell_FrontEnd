import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, relative as pathRelative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '..');
const generatedDir = resolve(repoRoot, 'src/types/generated');
const schemaSnapshotPath = resolve(generatedDir, 'ravell-api.openapi.json');
const outputPath = resolve(generatedDir, 'api.ts');
const backendSchemaPath = resolve(repoRoot, '../Ravell_BackEnd/openapi/ravell-api.openapi.json');
const sourceSchemaPath = process.env.OPENAPI_SCHEMA_PATH
  ? resolve(repoRoot, process.env.OPENAPI_SCHEMA_PATH)
  : (existsSync(backendSchemaPath) ? backendSchemaPath : schemaSnapshotPath);
const checkOnly = process.argv.includes('--check');

if (!existsSync(sourceSchemaPath)) {
  throw new Error(
    `OpenAPI schema not found at ${sourceSchemaPath}. ` +
    'Run the backend export command first or set OPENAPI_SCHEMA_PATH.'
  );
}

const schema = JSON.parse(readFileSync(sourceSchemaPath, 'utf8'));
const normalizedSchema = `${JSON.stringify(schema, null, 2)}\n`;
const generatedTypes = generateTypeScript(schema);

if (checkOnly) {
  assertFileMatches(schemaSnapshotPath, normalizedSchema);
  assertFileMatches(outputPath, generatedTypes);
  console.log('API contract generated files are current.');
} else {
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(schemaSnapshotPath, normalizedSchema, 'utf8');
  writeFileSync(outputPath, generatedTypes, 'utf8');
  console.log(`API schema snapshot written to ${relative(schemaSnapshotPath)}`);
  console.log(`API TypeScript contracts written to ${relative(outputPath)}`);
}

function assertFileMatches(path, expected) {
  if (!existsSync(path)) {
    throw new Error(`Generated file is missing: ${relative(path)}`);
  }

  const actual = readFileSync(path, 'utf8');
  if (actual !== expected) {
    throw new Error(`Generated file is out of date: ${relative(path)}`);
  }
}

function generateTypeScript(openApiSchema) {
  const schemas = openApiSchema.components?.schemas ?? {};
  const paths = openApiSchema.paths ?? {};
  const schemaLines = Object.entries(schemas).map(([name, value]) => {
    return `    ${quoteKey(name)}: ${schemaToType(value, { required: new Set(value.required ?? []) }, 4)};`;
  });

  const pathLines = Object.entries(paths).map(([path, pathItem]) => {
    return `    ${quoteKey(path)}: ${pathItemToType(pathItem)};`;
  });

  return [
    '/*',
    ' * Generated by scripts/generate-api-types.mjs.',
    ' * Do not edit manually. Regenerate after backend OpenAPI changes.',
    ' * Source contract: src/types/generated/ravell-api.openapi.json',
    ' */',
    '',
    'export interface components {',
    '  schemas: {',
    ...schemaLines,
    '  };',
    '}',
    '',
    'export interface paths {',
    ...pathLines,
    '}',
    '',
  ].join('\n');
}

function pathItemToType(pathItem) {
  const methods = ['get', 'post', 'put', 'patch', 'delete'];
  const methodLines = methods
    .filter((method) => pathItem?.[method])
    .map((method) => `      ${method}: ${operationToType(pathItem[method])};`);

  if (methodLines.length === 0) return '{}';

  return ['{', ...methodLines, '    }'].join('\n');
}

function operationToType(operation) {
  return [
    '{',
    `        parameters: ${parametersToType(operation.parameters ?? [])};`,
    `        responses: ${responsesToType(operation.responses ?? {})};`,
    '      }',
  ].join('\n');
}

function parametersToType(parameters) {
  const grouped = { path: [], query: [], header: [], cookie: [] };
  for (const parameter of parameters) {
    if (grouped[parameter.in]) grouped[parameter.in].push(parameter);
  }

  const groups = Object.entries(grouped)
    .filter(([, values]) => values.length > 0)
    .map(([location, values]) => {
      const properties = values.map((parameter) => {
        const optional = parameter.required ? '' : '?';
        return `          ${quoteKey(parameter.name)}${optional}: ${schemaToType(parameter.schema ?? {}, {}, 5)};`;
      });
      return [`        ${location}: {`, ...properties, '        };'].join('\n');
    });

  if (groups.length === 0) return 'Record<string, never>';

  return ['{', ...groups, '      }'].join('\n');
}

function responsesToType(responses) {
  const responseLines = Object.entries(responses).map(([status, response]) => {
    const jsonSchema = response.content?.['application/json']?.schema;
    const bodyType = jsonSchema ? schemaToType(jsonSchema, {}, 5) : 'unknown';

    return [
      `        ${quoteKey(status)}: {`,
      '          content: {',
      `            "application/json": ${bodyType};`,
      '          };',
      '        };',
    ].join('\n');
  });

  if (responseLines.length === 0) return 'Record<string, never>';

  return ['{', ...responseLines, '      }'].join('\n');
}

function schemaToType(schema, context = {}, indentLevel = 0) {
  if (!schema || Object.keys(schema).length === 0) return 'unknown';
  if (schema.$ref) return refToType(schema.$ref);

  if (schema.anyOf) {
    return schema.anyOf.map((item) => schemaToType(item, context, indentLevel)).join(' | ');
  }

  if (schema.oneOf) {
    return schema.oneOf.map((item) => schemaToType(item, context, indentLevel)).join(' | ');
  }

  if (schema.allOf) {
    return schema.allOf.map((item) => schemaToType(item, context, indentLevel)).join(' & ');
  }

  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => schemaToType({ ...schema, type }, context, indentLevel)).join(' | ');
  }

  if (schema.type === 'null') return 'null';
  if (schema.type === 'string') return 'string';
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'array') return `${schemaToType(schema.items ?? {}, context, indentLevel)}[]`;

  if (schema.type === 'object' || schema.properties) {
    return objectToType(schema, context, indentLevel);
  }

  return 'unknown';
}

function objectToType(schema, context, indentLevel) {
  const properties = schema.properties ?? {};
  const entries = Object.entries(properties);
  const required = new Set(schema.required ?? context.required ?? []);

  if (entries.length === 0) {
    return schema.additionalProperties ? 'Record<string, unknown>' : 'Record<string, never>';
  }

  const indent = '  '.repeat(indentLevel);
  const propertyIndent = '  '.repeat(indentLevel + 1);
  const lines = entries.map(([name, value]) => {
    const optional = required.has(name) ? '' : '?';
    return `${propertyIndent}${quoteKey(name)}${optional}: ${schemaToType(value, {}, indentLevel + 1)};`;
  });

  return ['{', ...lines, `${indent}}`].join('\n');
}

function refToType(ref) {
  const prefix = '#/components/schemas/';
  if (!ref.startsWith(prefix)) return 'unknown';

  return `components["schemas"][${JSON.stringify(ref.slice(prefix.length))}]`;
}

function quoteKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function relative(path) {
  return pathRelative(repoRoot, path).replaceAll('\\', '/');
}
